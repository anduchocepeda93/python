#input de numeros

numero1 = input("Ingrese el primer numero: ")
numero2 = input("Ingrese el segundo numero: ")

suma = float(numero1) + float(numero2)
resta = int(numero1) - int(numero2)
multiplicacion = int(numero1) * int(numero2)
division = int(numero1) / int(numero2)

print(f"La suma de ambos numeros es: {suma} ")
print(f"La diferencia de ambos numeros es: {resta} ")
print(f"El producto de ambos numeros es: {multiplicacion} ")
print(f"La division de ambos numeros es: {division} ")

